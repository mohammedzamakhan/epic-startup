#!/usr/bin/env node
/**
 * Generate package env.ts files from each package .env.schema via varlock.
 */
import fs from 'node:fs'
import path from 'node:path'
import { execSync } from 'node:child_process'

const root = process.cwd()
const varlock = path.join(root, 'node_modules/.bin/varlock')

if (!fs.existsSync(varlock)) {
	console.error(
		'varlock CLI not found. Run npm install from the monorepo root first.',
	)
	process.exit(1)
}

const packagesDir = path.join(root, 'packages')
const packages = fs
	.readdirSync(packagesDir, { withFileTypes: true })
	.filter((d) => d.isDirectory())
	.map((d) => d.name)
	.filter((name) =>
		fs.existsSync(path.join(packagesDir, name, '.env.schema')),
	)

for (const pkg of packages) {
	const pkgPath = path.join('packages', pkg)
	const srcDir = path.join(packagesDir, pkg, 'src')
	console.log(`codegen ${pkgPath}`)
	execSync(`${varlock} codegen --path ${pkgPath}`, {
		cwd: root,
		stdio: 'inherit',
	})
	// Metro/Vite/tsc import `./env.js`; Vitest sets VITEST=true to read process.env.
	fs.writeFileSync(
		path.join(srcDir, 'env.js'),
		[
			'// AUTOGENERATED by scripts/codegen-package-env.mjs — do not edit',
			"import { ENV as _ENV } from 'varlock/env';",
			'',
			'const testEnv = new Proxy({}, {',
			'\tget(_target, prop) {',
			'\t\tconst fromProcess = process.env[String(prop)];',
			'\t\tif (fromProcess !== undefined && fromProcess !== "") {',
			'\t\t\treturn fromProcess;',
			'\t\t}',
			'\t\ttry {',
			'\t\t\treturn _ENV[prop];',
			'\t\t} catch {',
			'\t\t\treturn undefined;',
			'\t\t}',
			'\t},',
			'});',
			'',
			'export const ENV =',
			"\ttypeof process !== 'undefined' && process.env.VITEST === 'true'",
			'\t\t? testEnv',
			'\t\t: _ENV;',
			'',
		].join('\n'),
	)
}
